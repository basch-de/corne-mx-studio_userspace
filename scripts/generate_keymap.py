#!/usr/bin/env python3
"""Offline translation of the committed ZMK snapshot. No device access."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LAYERS = ['macos', 'num', 'sym', 'nav', 'win', 'short', 'numpad', 'sys']
KEYS = dict(zip(
    'GRAVE BSLH SEMI SQT FSLH EQUAL COMMA DOT MINUS RET BSPC SPACE ESC TAB COLON TILDE DLLR PRCNT CARET AMPS ASTRK LPAR RPAR LBKT RBKT LBRC RBRC UNDER QMARK PIPE PLUS EXCL HASH AT PG_UP PG_DN DEL C_VOL_DN C_VOL_UP C_MUTE C_VOICE_COMMAND C_PWR LCTRL LGUI LALT LSHFT RCTRL RGUI RALT RSHFT'.split(),
    'GRV BSLS SCLN QUOT SLSH EQL COMM DOT MINS ENT BSPC SPC ESC TAB COLN TILD DLR PERC CIRC AMPR ASTR LPRN RPRN LBRC RBRC LCBR RCBR UNDS QUES PIPE PLUS EXLM HASH AT PGUP PGDN DEL VOLD VOLU MUTE ASST PWR LCTL LGUI LALT LSFT RCTL RGUI RALT RSFT'.split()))
MODS = {'LCTRL': 'MOD_LCTL', 'LGUI': 'MOD_LGUI', 'LALT': 'MOD_LALT', 'LSHFT': 'MOD_LSFT',
        'RCTRL': 'MOD_RCTL', 'RGUI': 'MOD_RGUI', 'RALT': 'MOD_RALT', 'RSHFT': 'MOD_RSFT'}

def key(expr):
    m = re.fullmatch(r'(LG|LC|LA|LS)\((.*)\)', expr)
    if m:
        return {'LG':'LGUI', 'LC':'LCTL', 'LA':'LALT', 'LS':'LSFT'}[m[1]] + '(' + key(m[2]) + ')'
    if re.fullmatch(r'N[0-9]', expr):
        return 'KC_' + expr[1:]
    return 'KC_' + KEYS.get(expr, expr)

RGB = {'RGB_HUD':'RM_HUED', 'RGB_HUI':'RM_HUEU', 'RGB_SAD':'RM_SATD',
       'RGB_SAI':'RM_SATU', 'RGB_BRD':'RM_VALD', 'RGB_BRI':'RM_VALU',
       'RGB_TOG':'RM_TOGG', 'RGB_EFF':'RM_NEXT'}

def translate(binding):
    a = binding.split()
    b = a[0][1:]
    if b == 'kp':
        if a[1] in ('C_VOICE_COMMAND', 'C_PWR'):
            return 'KC_NO', 'unsupported-hid-usage'
        return key(a[1]), 'direct'
    if b in ('hml', 'hmr'):
        return f'MT({MODS[a[1]]}, {key(a[2])})', 'approximate'
    if b in ('hlt', 'rhlt', 'rlt', 'lt'):
        return f'LT({a[1]}, {key(a[2])})', 'approximate'
    if b == 'tog':
        return f'TG({a[1]})', 'direct'
    if b == 'mt':
        if a[1] == 'DOT':
            return 'KC_COMM', 'split-interim'
        if a[2] == 'LG(SPACE)':
            return 'KC_HYPR', 'split-interim'
        assert a[1] == 'LA(LC(LSHFT))'
        return 'MEH_T(KC_QUOT)', 'approximate'
    if b == 'lcw':
        return 'MO(SHORT)', 'split-interim'
    if b == 'rgb_ug':
        return RGB[a[1]], 'approximate'
    if b in ('none', 'trans'):
        return ('KC_NO' if b == 'none' else 'KC_TRNS'), 'direct'
    if b in ('bt', 'ext_power', 'studio_unlock'):
        return 'KC_NO', 'omitted-platform-specific'
    if b == 'sys_reset':
        return 'QK_RBT', 'approximate'
    if b == 'bootloader':
        return 'QK_BOOT', 'approximate'
    raise ValueError(binding)

# Explicit and reviewable additions, all at documented positions (zero based).
OVERRIDES = {
    ('macos', 13): ('LT(SYS, KC_BSLS)', 'Right-hand SYS entry; tap remains backslash'),
    ('short', 0): ('CW_TOGG', 'Separate Caps Word toggle'),
    ('short', 14): ('LGUI(KC_SPC)', 'Separate Cmd+Space shortcut; base position holds Hyper'),
    ('numpad', 32): ('KC_DOT', 'Separate dot beside the existing NUMPAD toggle'),
    ('sys', 30): ('EE_CLR', 'Left EEPROM clear behind held SYS'),
    ('sys', 37): ('EE_CLR', 'Right EEPROM clear behind held SYS'),
}

def outputs():
    text = (ROOT / 'sources/corne_choc_pro.keymap').read_text()
    blocks = re.findall(r'display-name = "([a-z]+)";\s*bindings = <(.*?)>;', text, re.S)
    assert [n for n, _ in blocks] == LAYERS
    info = []
    lines = ['// SPDX-License-Identifier: GPL-2.0-or-later',
             '// Generated by scripts/generate_keymap.py; inspect docs/MAPPING.md.',
             '#include QMK_KEYBOARD_H', '',
             'enum layers { MACOS, NUM, SYM, NAV, WIN, SHORT, NUMPAD, SYS };', '',
             'const uint16_t PROGMEM keymaps[][MATRIX_ROWS][MATRIX_COLS] = {']
    for layer, block in blocks:
        bindings = [' '.join(x.split()) for x in re.findall(r'&[^&]+', block)]
        assert len(bindings) == 46, (layer, len(bindings))
        cells = []
        for pos, binding in enumerate(bindings):
            code, status = translate(binding)
            note = ''
            if (layer, pos) in OVERRIDES:
                code, note = OVERRIDES[layer, pos]
                status = 'documented-addition'
            cells.append(code)
            info.append(dict(layer=layer, position=pos, zmk=binding, qmk=code, status=status, note=note))
        lines.append(f'    [{layer.upper()}] = LAYOUT_split_3x6_3_ex2(')
        for start, stop in [(0,14), (14,28), (28,40), (40,46)]:
            lines.append('        ' + ', '.join(cells[start:stop]) + (',' if stop < 46 else ''))
        lines.append('    ),')
    lines += ['};', '', '// Standard QMK data table, no callback. All six thumbs are neutral triggers.',
              'const char chordal_hold_layout[MATRIX_ROWS][MATRIX_COLS] PROGMEM = {',
              "    {'L','L','L','L','L','L','L'},",
              "    {'L','L','L','L','L','L','L'},",
              "    {'L','L','L','L','L','L','L'},",
              "    {'*','*','*','*','*','*','*'},",
              "    {'R','R','R','R','R','R','R'},",
              "    {'R','R','R','R','R','R','R'},",
              "    {'R','R','R','R','R','R','R'},",
              "    {'*','*','*','*','*','*','*'},", '};', '',
              '#ifdef ENCODER_MAP_ENABLE',
              '// Keep all four manufacturer encoder actions on every populated layer.',
              'const uint16_t PROGMEM encoder_map[][NUM_ENCODERS][NUM_DIRECTIONS] = {']
    for i in range(8):
        lines.append(f'    [{i}] = {{ENCODER_CCW_CW(RGB_MOD, RGB_RMOD), ENCODER_CCW_CW(RGB_HUI, RGB_HUD), ENCODER_CCW_CW(RGB_VAI, RGB_VAD), ENCODER_CCW_CW(RGB_SAI, RGB_SAD)}},')
    lines += ['};', '#endif', '']
    md = ['# Positionszuordnung', '', 'Positionen sind nullbasiert und folgen der ZMK-Binding-Reihenfolge.',
          'Zeilen: 0–13, 14–27, 28–39, Daumen 40–45. `KC_NO` blockiert; `KC_TRNS` fällt durch.',
          'Die Spalte Status unterscheidet direkte Umsetzung, Näherung und dokumentierte Änderungen.', '',
          '| Layer | Position | ZMK | QMK | Status / Hinweis |', '|---|---:|---|---|---|']
    for c in info:
        md.append(f"| {c['layer']} | {c['position']} | `{c['zmk']}` | `{c['qmk']}` | {c['status']} {c['note']} |")
    return {
        'keyboards/keebart/corne_mx_pro/keymaps/studio/keymap.c': '\n'.join(lines),
        'docs/mapping.json': json.dumps(info, indent=2) + '\n',
        'docs/MAPPING.md': '\n'.join(md) + '\n',
    }

if __name__ == '__main__':
    for name, content in outputs().items():
        (ROOT / name).write_text(content)
